    add_p("Ключевое функциональное условие системы — защита от произвольного или преждевременного доступа к учебному материалу. Алгоритм функционирует следующим образом:")
    add_bullet("1. При первой авторизации студенту автоматически доступна только первая лекция курса (OrderIndex = 1).")
    add_bullet("2. Лекция №2 и последующие заблокированы: в интерфейсе отображается индикатор блокировки (🔒), а кнопка перехода неактивна.")
